#!/usr/bin/env node
// Writes src/config.generated.ts, which the TV app imports for its server URL.
// Runs before build/start/test/typecheck (npm pre* hooks).
//
//   HUDDLE_SERVER_URL=ws://192.168.1.20:8787/ws npm run build:debug
//
// Default: ws://<this Mac's LAN IP>:8787/ws. The Vega Virtual Device reaches the
// host on its LAN IP (and on 10.0.2.2); a phone can only use the LAN IP, so the
// TV uses it too and both sides agree on one address.
import {writeFileSync, readFileSync, existsSync} from 'node:fs';
import {networkInterfaces} from 'node:os';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

function lanAddress() {
  const found = [];
  for (const [name, addrs] of Object.entries(networkInterfaces())) {
    for (const a of addrs ?? []) {
      if (a.family !== 'IPv4' || a.internal || a.address.startsWith('169.254.')) continue;
      if (/^(utun|bridge|vmnet|vboxnet|docker|llw|awdl)/.test(name)) continue;
      found.push({name, address: a.address});
    }
  }
  found.sort((x, y) => Number(!x.name.startsWith('en')) - Number(!y.name.startsWith('en')) || x.name.localeCompare(y.name));
  return found[0]?.address;
}

const port = process.env.HUDDLE_PORT ?? '8787';
const serverUrl = process.env.HUDDLE_SERVER_URL ?? `ws://${lanAddress() ?? '10.0.2.2'}:${port}/ws`;
const householdId = process.env.HUDDLE_HOUSEHOLD ?? 'home';

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'config.generated.ts');
const body = `// Generated by scripts/write-config.mjs. Do not edit; gitignored.
export const SERVER_URL = ${JSON.stringify(serverUrl)};
export const HOUSEHOLD_ID = ${JSON.stringify(householdId)};
`;
if (!existsSync(out) || readFileSync(out, 'utf8') !== body) writeFileSync(out, body);
console.log(`[tv config] SERVER_URL=${serverUrl} HOUSEHOLD_ID=${householdId}`);
